create table public.enquiries (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  name text not null check (length(name) between 2 and 80),
  phone text not null check (phone ~ '^\+91[6-9][0-9]{9}$'),
  email text check (length(email) <= 160),
  service text not null check (service in ('GENERAL','CHITS','HEALTH_INSURANCE','LIFE_INSURANCE','LOANS','REAL_ESTATE')),
  callback text not null,
  message text not null default '' check (length(message) <= 1200),
  status text not null default 'NEW' check (status in ('NEW','FOLLOW_UP','CONTACTED','CLOSED')),
  notes text not null default '' check (length(notes) <= 2000),
  source text not null default 'WEBSITE',
  ip_hash text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index enquiries_status_created on public.enquiries(status,created_at desc);
create index enquiries_phone_service on public.enquiries(phone,service,created_at desc);
create table public.request_limits (
  ip_hash text not null,
  window_start timestamptz not null,
  request_count integer not null,
  primary key(ip_hash,window_start)
);

alter table public.enquiries enable row level security;
alter table public.request_limits enable row level security;
revoke all on public.enquiries,public.request_limits from public,anon,authenticated;
grant select,insert,update,delete on public.enquiries,public.request_limits to service_role;
grant usage,select on sequence public.enquiries_id_seq to service_role;

-- Only the server service-role client may call this transaction. Visitors cannot
-- call it directly with a publishable key or read customer details through the API.
create function public.submit_enquiry(
  p_name text,p_phone text,p_email text,p_service text,p_callback text,p_message text,p_ip_hash text
) returns jsonb language plpgsql security invoker set search_path='' as $$
declare
  existing_reference text;
  new_id bigint;
  new_reference text;
  current_window timestamptz := date_trunc('hour',now());
  attempts integer;
begin
  if p_ip_hash is null or length(p_ip_hash)=0 then raise exception 'INVALID_REQUEST'; end if;
  -- Serialize duplicate checks for a phone/service across simultaneous requests.
  perform pg_advisory_xact_lock(hashtextextended(p_phone || ':' || p_service,0));
  select reference into existing_reference from public.enquiries
    where phone=p_phone and service=p_service and created_at>now()-interval '15 minutes'
    order by created_at desc limit 1;
  if existing_reference is not null then return jsonb_build_object('reference',existing_reference,'duplicate',true); end if;

  insert into public.request_limits(ip_hash,window_start,request_count) values(p_ip_hash,current_window,1)
    on conflict(ip_hash,window_start) do update set request_count=public.request_limits.request_count+1
    returning request_count into attempts;
  if attempts>5 then raise exception 'RATE_LIMITED'; end if;
  delete from public.request_limits where window_start<now()-interval '2 days';

  insert into public.enquiries(reference,name,phone,email,service,callback,message,ip_hash)
    values('pending-'||md5(random()::text||clock_timestamp()::text),p_name,p_phone,p_email,p_service,p_callback,p_message,p_ip_hash)
    returning id into new_id;
  new_reference:='SG-'||extract(year from now())::text||'-'||lpad(new_id::text,greatest(6,length(new_id::text)),'0');
  update public.enquiries set reference=new_reference where id=new_id;
  return jsonb_build_object('reference',new_reference,'duplicate',false);
end;
$$;
revoke all on function public.submit_enquiry(text,text,text,text,text,text,text) from public,anon,authenticated;
grant execute on function public.submit_enquiry(text,text,text,text,text,text,text) to service_role;
